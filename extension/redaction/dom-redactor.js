/**
 * Veilex — DOM Redactor Module
 * 
 * Sanitizes the extracted DOM snapshot by replacing actual text
 * with privacy tokens (e.g., "[EMAIL]") before sending it to the server.
 */

/**
 * Applies token replacement to the DOM snapshot based on PII detections.
 * 
 * @param {Object} domSnapshot - The original DOM snapshot
 * @param {Array} detections - The detected PII items
 * @returns {Object} A new, sanitized DOM snapshot object
 */
export function redactDOM(domSnapshot, detections) {
  if (!domSnapshot) return null;
  
  // Deep clone to avoid mutating the original
  const sanitized = JSON.parse(JSON.stringify(domSnapshot));

  // Helper function to recursively walk and redact the DOM tree
  function walkAndRedact(node) {
    if (!node) return;

    // Redact text nodes based on text matching
    if (node.text && typeof node.text === 'string') {
      let newText = node.text;
      
      // We iterate over all text-based detections (like regex output)
      // and replace the exact string matches. 
      // Detections generated by the regex detector will have `token` and `text` (or just match the regex).
      // Since detections from regex already have the matched text in `detection.value` or similar:
      for (const det of detections) {
        if (det.value && typeof det.value === 'string') {
          // Replace all occurrences of the detected PII value with its token
          const token = det.token || `[${det.type}_REDACTED]`;
          // Escape regex special chars for the replacement
          const escapedValue = det.value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
          const regex = new RegExp(escapedValue, 'g');
          newText = newText.replace(regex, token);
        }
      }
      
      node.text = newText;
    }

    // Also redact input values
    if (node.value && typeof node.value === 'string') {
      let newValue = node.value;
      for (const det of detections) {
        if (det.value && typeof det.value === 'string') {
          const token = det.token || `[${det.type}_REDACTED]`;
          const escapedValue = det.value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
          const regex = new RegExp(escapedValue, 'g');
          newValue = newValue.replace(regex, token);
        }
      }
      node.value = newValue;
    }

    // Traverse children
    if (node.children && Array.isArray(node.children)) {
      for (const child of node.children) {
        walkAndRedact(child);
      }
    }
  }

  // Execute the recursive walk
  walkAndRedact(sanitized);

  return sanitized;
}
